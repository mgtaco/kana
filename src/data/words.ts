/**
 * The word pool for the reading drill.
 *
 * Everything here is written in hiragana alone — no kanji, no katakana, no
 * long-vowel bar — because the point is to read the characters, not to look up
 * a word. `romaji` is the plain Hepburn reading; the drill accepts far more
 * than this one spelling (see `lib/kanaText.ts`), and a dev-only self-check in
 * that file asserts this spelling is among the ones it would accept.
 *
 * Tiers order the pool rather than gate it — `wordsReadableWith` does the real
 * gating, from the characters a learner has actually met:
 *
 *   1  basic kana only, short, weighted towards the first rows of the chart,
 *      so that words become readable two or three lessons in;
 *   2  adds dakuten and handakuten;
 *   3  adds yōon, and the longer compounds.
 *
 * The per-character `example` fields in `hiragana.ts` are a different thing and
 * stay as they are: one word per character, chosen for the chart.
 */

