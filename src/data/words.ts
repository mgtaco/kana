export const WORDS_BY_TEXT = new Map(WORDS.map((entry) => [entry.word, entry]));

/**
 * っ is a small つ and has no reading of its own, so a word containing one is
 * readable exactly when つ is. Everything else has to be known outright.
 */
const UNIT_REQUIREMENT: Record<string, string> = { っ: 'つ' };

/** Every character a word is spelled with, as units the learner would recognise. */
export function charsRequiredFor(word: string): string[] {
  return splitKana(word).map((unit) => UNIT_REQUIREMENT[unit] ?? unit);
}

/** The words that can be read using only the given characters. */
export function wordsReadableWith(allowed: Set<string>): Word[] {
  return WORDS.filter((entry) =>
    charsRequiredFor(entry.word).every((char) => allowed.has(char)),
  );
}
